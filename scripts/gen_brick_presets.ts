// Lays the brickwork presets' shapes (src/presets/brickPresetShapes.ts) and
// writes the bricks to src/presets/brickPresetData.ts, so loading a preset
// does not lay a few thousand bricks on the page.
//
// Usage:  npx vite-node scripts/gen_brick_presets.ts

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { layBricks } from '../src/utils/brickwork';
import { CASTLE_OPTIONS, castleShape, encodeBricks, SMOKER_OPTIONS, smokerShape } from '../src/presets/brickPresetShapes';

const rows = (data: number[]) => {
  const lines: string[] = [];
  for (let i = 0; i < data.length; i += 8) lines.push(`  ${data.slice(i, i + 8).join(', ')},`);
  return lines.join('\n');
};

const smoker = encodeBricks(layBricks(smokerShape(), SMOKER_OPTIONS).bricks);
const castle = encodeBricks(layBricks(castleShape(), CASTLE_OPTIONS).bricks);

const out = `// Regenerated by scripts/gen_brick_presets.ts from src/presets/brickPresetShapes.ts.
// Do not edit by hand: change the shapes there and run the script.
// x, y, z, length, depth (mm), angle (rad), flags (1 header, 2 closer, 4 cut), course.

export const SMOKER_BRICKS: readonly number[] = [
${rows(smoker)}
];

export const CASTLE_BRICKS: readonly number[] = [
${rows(castle)}
];
`;
writeFileSync(resolve(__dirname, '../src/presets/brickPresetData.ts'), out);
console.log(`smoker ${smoker.length / 8} bricks, castle ${castle.length / 8}`);
